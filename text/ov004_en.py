# build.py passes the patched menu font as MENU_FONT; otherwise (tools/fill_text.py)
# it is read from extracted/ (tools/extract.py).
_FONT = globals().get("MENU_FONT") or _uilint.load_font(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "..", "extracted", "fpg", "009.bin"))


def _w(text):
    return _uilint.measure(text, _FONT)[1]


# Appearance: the game draws the label, puts the <> arrow 20 px before where
# the label ended and the value right after it. The Japanese ends in "#x12,,"
# whose ASCII comma was a 12 px cell in the original font (now narrow), so
# pad with a plain gap instead and end every label at the same x.
